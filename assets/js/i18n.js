let currentLang = localStorage.getItem('CVISUAL_LANG') || 'fr';

export function getLang() {
    return currentLang;
}

export function setLang(lang) {
    if (translations[lang]) {
        currentLang = lang;
        localStorage.setItem('CVISUAL_LANG', lang);
        document.documentElement.setAttribute('lang', lang);
        window.dispatchEvent(new CustomEvent('cvisual:lang-changed', { detail: { lang } }));
        return true;
    }
    return false;
}

export function t(path, params = {}) {
    const keys = path.split('.');
    let result = translations[currentLang];
    
    for (const key of keys) {
        if (result && result[key] !== undefined) {
            result = result[key];
        } else {
            // Repli sur le français si clé manquante
            let fallback = translations['fr'];
            for (const fKey of keys) {
                if (fallback && fallback[fKey] !== undefined) {
                    fallback = fallback[fKey];
                } else {
                    return path;
                }
            }
            result = fallback;
            break;
        }
    }

    if (typeof result === 'string') {
        return result.replace(/\{(\w+)\}/g, (_, k) => params[k] !== undefined ? params[k] : `{${k}}`);
    }

    return result || path;
}

window.t = t;
window.setLang = setLang;
window.getLang = getLang;
